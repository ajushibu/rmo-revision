#!/usr/bin/env python3
"""Mirror the app's width media queries (max-width 1099px = md, 760px = sm) as html[data-w~=...] rules.
Text size zooms the app, so the layout must follow the width the app *seems* to have (look.js sets data-w).
Run after changing any such @media block in style.css."""
import re
p = 'style.css'
s = open(p).read()
B, E = '/* BEGIN w-mirror (generated by scripts/mirror_css.py) */', '/* END w-mirror */'
if B in s:
    s = s[:s.index(B)].rstrip() + '\n' + s[s.index(E) + len(E):]
def blocks(head):
    out, i = [], 0
    while True:
        i = s.find(head, i)
        if i < 0: break
        j = s.index('{', i); d = 1; k = j + 1
        while d:
            d += {'{': 1, '}': -1}.get(s[k], 0); k += 1
        out.append(s[j + 1:k - 1]); i = k
    return out
res = [B]
for head, tok in (('@media (max-width: 1099px)', 'md'), ('@media (max-width: 760px)', 'sm')):
    for body in blocks(head):
        for m in re.finditer(r'([^{}]+)\{([^{}]*)\}', body):
            sels = [x.strip() for x in m.group(1).split(',') if x.strip()]
            res.append(', '.join('html[data-w~="%s"] %s' % (tok, x) for x in sels) + ' {' + m.group(2) + '}')
res.append(E)
open(p, 'w').write(s.rstrip() + '\n\n' + '\n'.join(res) + '\n')
